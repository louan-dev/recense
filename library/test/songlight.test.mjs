// FEAT-20 (iOS syllable light, route A): iPhone, iPad and the Mac fit with the one Swift Cadence (shared/ShowsKit/Cadence)
// and light each word with SongLight.fill; the web player runs this cadence.js. This keeps the two from drifting:
//   · shared/ShowsKit/Tests/ShowsKitTests/Fixtures/songlight.json holds a song fitted here and the light's fill at
//     sample moments; ShowsKit's SongLightTests checks the Swift engine and fill against the same numbers.
// Regenerate the fixture after changing cadence.js: UPDATE=1 node test/songlight.test.mjs
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "../src/client/cadence.js");
const fixDir = join(here, "../../shared/ShowsKit/Tests/ShowsKitTests/Fixtures");
const fix = join(fixDir, "songlight.json");

createRequire(import.meta.url)("../src/client/cadence.js");
const C = globalThis.Cadence;

// the cadence.test.mjs voice: notes (start, end, MIDI × 100) on a stem voiced throughout
const voice = (notes, secs = 6) => {
  const n = secs * 100, pitch = new Array(n).fill(0), db = new Array(n).fill(-200);
  for (const [a, b, m] of notes) for (let k = Math.round(a * 100); k < Math.round(b * 100); k++) pitch[k] = m;
  return { format: 1, source: "vocals", hop: 0.01, floor: -57.5, db, voiced: new Array(n).fill(1),
    onset: new Array(n).fill(0), clarity: new Array(n).fill(90), pitch };
};
const notes = [[1.0, 1.15, 6500], [1.2, 1.35, 6530], [1.4, 1.55, 6400], [1.6, 1.85, 6450],
  [2.0, 2.4, 6200], [2.42, 3.0, 6000], [3.2, 3.3, 6530], [3.34, 4.5, 6700]];
const lines = [{ id: 2000001, s: 1.2, e: 4.2, text: "Variations on a dream", words: [
  { t: "Variations", s: 1.2, e: 1.6 }, { t: "on", s: 1.6, e: 2.1 }, { t: "a", s: 3.6, e: 3.7 }, { t: "dream", s: 3.9, e: 4.2 }] }];

function build() {
  const fitted = C.pin(C.fit(lines, voice(notes), 0));
  const words = fitted[0].words;
  // the light at every 50 ms across the line, as gallery.js fillOf asks (n = the word's code points)
  const samples = [];
  for (let t = 0.9; t <= 4.6; t = Math.round((t + 0.05) * 100) / 100)
    for (let i = 0; i < words.length; i++) samples.push([i, t, Math.round(C.fill(words[i], t, Array.from(words[i].t).length) * 1e6) / 1e6]);
  // a word the listener timed (k) and one traced, as pin leaves them, with the fill they get
  const pinned = C.pin([{ id: 1, s: 0, e: 2, words: [{ t: "hold", s: 0, e: 1, tm: { s: 0.2, e: 1.2, k: 0.6 } },
    { t: "trace", s: 1.2, e: 2, tm: { s: 1.2, e: 2, k: 0, c: [0, 0.1, 0.8, 1] } }] }])[0].words;
  const pins = [];
  for (let t = 0; t <= 2.1; t = Math.round((t + 0.1) * 100) / 100)
    for (let i = 0; i < pinned.length; i++) pins.push([i, t, Math.round(C.fill(pinned[i], t, Array.from(pinned[i].t).length) * 1e6) / 1e6]);
  return { note: "generated by library/test/songlight.test.mjs from cadence.js; do not edit by hand",
    notes, lines, fitted: words.map((w) => ({ t: w.t, s: w.s, e: w.e, syl: w.syl || null, un: !!w.un })), samples,
    pinned: pinned.map((w) => ({ t: w.t, s: w.s, e: w.e, k: w.k ?? null, c: w.c ?? null })), pins };
}

test("the Swift fill fixture is current with cadence.js", () => {
  const now = build();
  if (process.env.UPDATE) { mkdirSync(fixDir, { recursive: true }); writeFileSync(fix, JSON.stringify(now, null, 1) + "\n"); }
  const was = JSON.parse(readFileSync(fix, "utf8"));
  assert.deepEqual(was, now, "regenerate: UPDATE=1 node test/songlight.test.mjs");
  // and the fixture says something: Variations is sung in four syllables, lit through them in order
  assert.equal(now.fitted[0].syl.length, 4);
  const v = now.samples.filter((x) => x[0] === 0).map((x) => x[2]);
  for (let i = 1; i < v.length; i++) assert.ok(v[i] >= v[i - 1], "never goes back");
  assert.ok(v.some((x) => x > 0 && x < 1), "a partial fill while it is sung");
});
